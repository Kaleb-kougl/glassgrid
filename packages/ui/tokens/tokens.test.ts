/**
 * @vitest-environment node
 */
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

interface Generator {
  tokenOutputs(): Record<string, string>;
  driftedOutputs(dir?: string): string[];
}

const require = createRequire(import.meta.url);
const generator = require('./generate.js') as Generator;
const OUTPUTS = ['glassgrid.css', 'glassgrid.tokens.json', 'glassgrid.resolved.light.json', 'glassgrid.resolved.dark.json', 'checks.json'];

describe('design tokens', () => {
  it('regenerating produces byte-identical outputs (drift check)', () => {
    const generated = generator.tokenOutputs();
    expect(Object.keys(generated).sort()).toEqual([...OUTPUTS].sort());
    for (const name of OUTPUTS) {
      expect(readFileSync(join(import.meta.dirname, name), 'utf8'), name).toBe(generated[name]);
    }
    expect(generator.driftedOutputs()).toEqual([]);
  });

  it('reports a hand-edited output as drifted', () => {
    const dir = mkdtempSync(join(tmpdir(), 'gg-tokens-'));
    try {
      for (const [name, content] of Object.entries(generator.tokenOutputs())) writeFileSync(join(dir, name), content);
      writeFileSync(join(dir, 'glassgrid.css'), generator.tokenOutputs()['glassgrid.css']?.replace('#0d1013', '#000000') ?? '');
      expect(generator.driftedOutputs(dir)).toEqual(['glassgrid.css']);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it('keeps the generated-file header on the stylesheet', () => {
    expect(readFileSync(join(import.meta.dirname, 'glassgrid.css'), 'utf8')).toMatch(/^\/\* Glassgrid design tokens — generated by tokens\/build-tokens\.js\. Do not edit by hand\./);
  });

  it('passes every contrast check it records', () => {
    const checks = JSON.parse(readFileSync(join(import.meta.dirname, 'checks.json'), 'utf8')) as {
      contrast: { label: string; pass: string }[];
    };
    expect(checks.contrast.filter((row) => row.pass === 'FAIL').map((row) => row.label)).toEqual([]);
  });
});
